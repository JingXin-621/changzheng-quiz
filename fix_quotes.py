# -*- coding: utf-8 -*-
"""修复 index.html 中 JavaScript 字符串里的中文引号冲突"""

with open('index.html', 'r', encoding='utf-8') as f:
    html = f.read()

# 提取 <script> 内容
start = html.index('<script>') + 8
end = html.index('</script>', start)
script = html[start:end]

# 清理：把 JS 字符串内容中所有 ASCII 双引号对应的中文引号替换为 Unicode 中文引号
# 策略：在 JavaScript 双引号字符串内部，中文文本中不应该出现 ASCII 双引号
# 我们把所有 "xxx" 形式的中文引用（即双引号内是中文内容）替换为「xxx」

import re

# 匹配模式：一个 ASCII 双引号，后面紧跟中文/字母/数字，前面不是字母数字（即不是 JS 语法的一部分）
# 这是一个启发式方法

# 更直接的方法：列出所有需要替换的模式
fixes = [
    # q字段中的引号
    ('被称为"红色故都"', '被称为「红色故都」'),
    ('被称为"党的历史上生死攸关的转折点"', '被称为「党的历史上生死攸关的转折点」'),
    ('纠正了"左"倾军事路线错误', '纠正了「左」倾军事路线错误'),
    ('写道："红军不怕远征难，万水千山只等闲。"', '写道：「红军不怕远征难，万水千山只等闲。」'),
    ('写道"不到长城非好汉，屈指行程二万"', '写道「不到长城非好汉，屈指行程二万」'),
    ('称之为"得意之笔"', '称之为「得意之笔」'),
    ('中"雄关漫道真如铁，而今迈步从头越"成为', '中「雄关漫道真如铁，而今迈步从头越」成为'),
    ('他说"骡子比人金贵，它能救战士的命"', '他说「骡子比人金贵，它能救战士的命」'),
    ('百姓"三年不饮湘江水，十年不食湘江鱼"', '百姓「三年不饮湘江水，十年不食湘江鱼」'),
    ('中"大渡桥横铁索寒"描写', '中「大渡桥横铁索寒」描写'),
    ('e:""铁索寒"写出', 'e:"「铁索寒」写出'),
    ('以"更喜岷山千里雪，三军过后尽开颜"收尾', '以「更喜岷山千里雪，三军过后尽开颜」收尾'),
    ('成立"三人军事指挥小组"', '成立「三人军事指挥小组」'),
    ('q:""不到长城非好汉"出自', 'q:"「不到长城非好汉」出自'),
    ('反"围剿"失败', '反「围剿」失败'),
    ('于王明"左"倾错误导致第五次反"围剿"失败', '于王明「左」倾错误导致第五次反「围剿」失败'),
    ('"左"倾', '「左」倾'),
    ('"围剿"', '「围剿」'),
    # q字段中的书名号引用
    ('q:""飞夺泸定桥"发生', 'q:"「飞夺泸定桥」发生'),
    ('q:""半条被子"的故事', 'q:"「半条被子」的故事'),
    ('q:""金色的鱼钩"中', 'q:"「金色的鱼钩」中'),
    ('穿越的"松潘草地"位于', '穿越的「松潘草地」位于'),
    ('q:""巧渡金沙江"红军', 'q:"「巧渡金沙江」红军'),
    ('q:""雪山上的军需处长"为什么', 'q:"「雪山上的军需处长」为什么'),
    ('q:""一袋干粮"的故事', 'q:"「一袋干粮」的故事'),
    # 更多...
    ('第五次反"围剿"失败', '第五次反「围剿」失败'),
    ('反"围剿"', '反「围剿」'),
    ('"左"倾错误', '「左」倾错误'),
    ('"左"倾', '「左」倾'),
]

count = 0
for old, new in fixes:
    if old in script:
        script = script.replace(old, new)
        count += 1

print(f'Fixed {count} quote patterns')

# 验证：检查是否还有未处理的冲突引号
# 查找 " 后紧跟中文字符的模式（可能是残留问题）
remaining = re.findall(r'“[^”]*”', script)  # Unicode中文引号，已经是OK的
print(f'Unicode Chinese quotes found: {len(remaining)}')

html = html[:start] + script + html[end:]

with open('index.html', 'w', encoding='utf-8') as f:
    f.write(html)

print('Done!')
